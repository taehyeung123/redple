/**
 * 레드랭크 AI 원고 생성은 본문을 마크다운 형식(##소제목, **강조**)으로 만든다
 * (레드랭크 웹사이트 자체도 이걸 그대로 평문으로 보여준다 — 렌더링 안 함).
 * 네이버 에디터에 그대로 붙여넣으면 별표(**)·해시(##) 기호가 그대로 노출되므로,
 * 자동입력 전에는 반드시 이 함수로 정리한 텍스트를 써야 한다.
 */
export function markdownToPlainText(md) {
    if (!md) return '';
    return md
        // 코드블록/인라인코드 백틱 제거
        .replace(/```[\s\S]*?```/g, (m) => m.replace(/```/g, ''))
        .replace(/`([^`]+)`/g, '$1')
        // 소제목(## / ### ...) → 그냥 그 줄의 텍스트만 남기고 앞뒤에 빈 줄로 구분
        .replace(/^#{1,6}\s*(.+)$/gm, '\n$1\n')
        // 굵게/기울임 — **텍스트**, __텍스트__, *텍스트*, _텍스트_
        .replace(/\*\*([^*]+)\*\*/g, '$1')
        .replace(/__([^_]+)__/g, '$1')
        .replace(/\*([^*]+)\*/g, '$1')
        .replace(/_([^_]+)_/g, '$1')
        // 목록 기호(-, *, +) → 가운뎃점으로
        .replace(/^[ \t]*[-*+]\s+/gm, '· ')
        // 인용(>) 기호 제거
        .replace(/^>\s?/gm, '')
        // 연속 빈 줄 3개 이상 → 2개로
        .replace(/\n{3,}/g, '\n\n')
        .trim();
}
